package vn.xuantruong.transport.service;

import java.util.List;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.env.Environment;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

@Component
public class DatabaseInitializer implements ApplicationRunner {
    private final JdbcTemplate jdbc;
    private final PasswordService passwords;
    private final Environment environment;

    public DatabaseInitializer(JdbcTemplate jdbc, PasswordService passwords, Environment environment) {
        this.jdbc = jdbc;
        this.passwords = passwords;
        this.environment = environment;
    }

    @Override
    @Transactional
    public void run(ApplicationArguments args) {
        createSchema();
        if (!Boolean.parseBoolean(environment.getProperty("SEED_DATA", "true"))) return;
        seedAdmin();
        seedVehicles();
    }

    private void createSchema() {
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS admins (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  username TEXT UNIQUE NOT NULL,
                  password_hash TEXT NOT NULL,
                  salt TEXT NOT NULL,
                  ho_ten TEXT,
                  role TEXT DEFAULT 'owner' CHECK (role IN ('owner', 'staff')),
                  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS customers (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  ten TEXT NOT NULL,
                  dien_thoai TEXT UNIQUE NOT NULL,
                  email TEXT,
                  ghi_chu TEXT,
                  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS bookings (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL,
                  ho_ten TEXT NOT NULL,
                  dien_thoai TEXT NOT NULL,
                  email TEXT,
                  diem_lay_hang TEXT NOT NULL,
                  diem_giao_hang TEXT NOT NULL,
                  loai_hang TEXT,
                  trong_luong DOUBLE PRECISION,
                  ghi_chu TEXT,
                  gia_tri DOUBLE PRECISION,
                  trang_thai TEXT DEFAULT 'moi' CHECK (trang_thai IN ('moi', 'da_bao_gia', 'dang_chay', 'hoan_thanh', 'huy')),
                  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS vehicles (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  ten TEXT NOT NULL,
                  bien_so TEXT UNIQUE NOT NULL,
                  loai TEXT,
                  tai_trong TEXT,
                  trang_thai TEXT DEFAULT 'san_sang' CHECK (trang_thai IN ('san_sang', 'dang_chay', 'bao_duong')),
                  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS trips (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  booking_id BIGINT REFERENCES bookings(id) ON DELETE SET NULL,
                  vehicle_id BIGINT REFERENCES vehicles(id) ON DELETE SET NULL,
                  tai_xe TEXT,
                  ngay_khoi_hanh TEXT,
                  trang_thai TEXT DEFAULT 'cho_chay' CHECK (trang_thai IN ('cho_chay', 'dang_chay', 'hoan_thanh', 'huy')),
                  ghi_chu TEXT,
                  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_bookings_customer_id ON bookings(customer_id)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_bookings_created_at ON bookings(created_at)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_trips_booking_id ON trips(booking_id)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_trips_vehicle_id ON trips(vehicle_id)");
    }

    private void seedAdmin() {
        Long count = jdbc.queryForObject("SELECT COUNT(*) FROM admins", Long.class);
        if (count != null && count == 0) {
            String salt = passwords.newSalt();
            jdbc.update("INSERT INTO admins (username, password_hash, salt, ho_ten, role) VALUES (?, ?, ?, ?, 'owner')",
                    "admin", passwords.hash("xuantruong123", salt), salt, "Quan tri vien");
        }
    }

    private void seedVehicles() {
        Long count = jdbc.queryForObject("SELECT COUNT(*) FROM vehicles", Long.class);
        if (count != null && count > 0) return;
        List<String[]> vehicles = new java.util.ArrayList<>();
        vehicles.add(new String[]{"Xe tai nho 1", "CHUA-CAP-NHAT-01", "thung_kin", "500kg-1T"});
        vehicles.add(new String[]{"Xe tai nho 2", "CHUA-CAP-NHAT-02", "thung_kin", "500kg-1T"});
        for (int i = 1; i <= 6; i++) vehicles.add(new String[]{"Xe 2.5 tan " + i, "CHUA-CAP-NHAT-1" + i, "mui_bat", "2-2.5T"});
        for (int i = 1; i <= 3; i++) vehicles.add(new String[]{"Xe 5 tan " + i, "CHUA-CAP-NHAT-2" + i, "mui_bat", "5T"});
        for (int i = 1; i <= 3; i++) vehicles.add(new String[]{"Xe 10 tan " + i, "CHUA-CAP-NHAT-3" + i, "mui_bat", "8-10T"});
        vehicles.add(new String[]{"Xe dong lanh 1", "CHUA-CAP-NHAT-41", "dong_lanh", "1.5-10T"});
        jdbc.batchUpdate("INSERT INTO vehicles (ten, bien_so, loai, tai_trong) VALUES (?, ?, ?, ?)", vehicles);
    }
}
